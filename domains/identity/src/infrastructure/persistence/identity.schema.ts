import { relations, sql } from 'drizzle-orm';
import {
  boolean,
  check,
  index,
  pgSchema,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';
import { TENANT_ROLE_VALUES } from '../../domain/tenant-role.js';
import { USER_ROLES } from '../../domain/user-role.js';

/*
 * Identity tables (drizzle-kit reads this file: ONLY drizzle-orm imports + dependency-free
 * relative files — see blueprint §3.6). Column names come from `casing: 'snake_case'`.
 *
 * Every table and enum lives in the `identity` Postgres schema, with identity's own migration
 * history (./migrations, generated by ../../../drizzle.config.ts, bookkeeping in
 * `identity.__drizzle_migrations`). Raw SQL qualifies names (`identity.users`): no role's
 * search_path includes `identity`.
 *
 * Ids are uuidv7 generated by the application (known before INSERT: domain events, the session
 * id doubles as the refresh token `jti`). The Postgres 18 `uuidv7()` DEFAULT only covers raw SQL
 * inserts (seeds, psql). uuidv7 is time-ordered, so `ORDER BY id DESC` = newest first and the PK
 * index serves keyset pagination (scanned backwards — no extra index needed).
 *
 * Search: `ILIKE '%q%'` on email/display_name cannot use a btree, so `users_search_trgm_idx` is a
 * pg_trgm GIN index on both columns (the `OR` becomes a BitmapOr). Trigrams need >= 3 characters,
 * hence `IDENTITY_LIMITS.SEARCH_MIN_LENGTH`. drizzle-kit does not emit extensions: pg_trgm comes
 * from @platform/database's platform set (in schema public), which always runs before this history.
 */

/**
 * The `identity` Postgres schema. Exported: drizzle-kit only emits `CREATE SCHEMA` (and records
 * it in the snapshot) for exported schemas.
 */
export const identityPgSchema = pgSchema('identity');

const timestamptz = () => timestamp({ withTimezone: true, precision: 3, mode: 'date' });

/** RBAC roles (values = @platform/auth `Role`). */
export const userRole = identityPgSchema.enum('user_role', USER_ROLES);

/** Tenant roles (values = @platform/common `TENANT_ROLES`). */
export const tenantRole = identityPgSchema.enum('tenant_role', TENANT_ROLE_VALUES);

export const users = identityPgSchema.table(
  'users',
  {
    id: uuid().primaryKey().default(sql`uuidv7()`),
    /** Normalised (trimmed + lowercase) before it gets here, so a plain unique constraint is enough. */
    email: text().notNull().unique('users_email_unique'),
    passwordHash: text().notNull(),
    displayName: text().notNull(),
    // Qualified: the cast is resolved when CREATE TABLE runs, and `identity` is not on search_path.
    roles: userRole().array().notNull().default(sql`ARRAY['user']::identity.user_role[]`),
    createdAt: timestamptz().notNull().defaultNow(),
    updatedAt: timestamptz()
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (t) => [
    // admin user search: `email ILIKE '%q%' OR display_name ILIKE '%q%'`.
    index('users_search_trgm_idx').using(
      'gin',
      t.email.op('gin_trgm_ops'),
      t.displayName.op('gin_trgm_ops'),
    ),
  ],
);

export const sessions = identityPgSchema.table(
  'sessions',
  {
    /** = the refresh token's `jti`. */
    id: uuid().primaryKey(),
    userId: uuid()
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** sha256 hex of the refresh token (never the token itself). */
    refreshTokenHash: text().notNull(),
    userAgent: text(),
    ip: text(),
    expiresAt: timestamptz().notNull(),
    revokedAt: timestamptz(),
    replacedById: uuid(),
    createdAt: timestamptz().notNull().defaultNow(),
  },
  (t) => [
    // "revoke all sessions of a user" (reuse detection, sign-out everywhere) + FK cascade.
    index('sessions_user_id_idx').on(t.userId),
    // hourly purge `WHERE expires_at <= now()`.
    index('sessions_expires_at_idx').on(t.expiresAt),
  ],
);

// citus: reference (users, tenants and memberships are reference tables: sharding design §2.2)
export const tenants = identityPgSchema.table(
  'tenants',
  {
    id: uuid().primaryKey().default(sql`uuidv7()`),
    /** DNS-label shaped (`TENANT_SLUG_PATTERN`); personal workspaces derive it from the email. */
    slug: text().notNull().unique('tenants_slug_unique'),
    name: text().notNull(),
    /** The workspace registration created; `false` for tenants created through the API. */
    personal: boolean().notNull().default(false),
    createdAt: timestamptz().notNull().defaultNow(),
  },
  // The nil UUID is PLATFORM_TENANT_ID (@platform/common): never issued as a tenant id. Literal on
  // purpose: drizzle-kit loads this file without workspace packages (identity.migrations.spec pins it).
  () => [
    check('tenants_id_not_platform', sql`"id" <> '00000000-0000-0000-0000-000000000000'::uuid`),
  ],
);

// citus: reference (a STABLE policy helper reads it on every node: sharding design §2.2)
export const memberships = identityPgSchema.table(
  'memberships',
  {
    tenantId: uuid()
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    userId: uuid()
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    /** Canonical order (owner, admin, member), deduplicated, never empty. */
    roles: tenantRole().array().notNull(),
    /** Set by register, login and switch (a replicated write on Citus), never by refresh. */
    lastActiveAt: timestamptz(),
    createdAt: timestamptz().notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ name: 'memberships_tenant_id_user_id_pk', columns: [t.tenantId, t.userId] }),
    // "most recently active membership" at login (MembershipsRepository.findMostRecentForUser).
    index('memberships_user_id_last_active_at_idx').on(t.userId, t.lastActiveAt.desc().nullsLast()),
    check('memberships_roles_not_empty', sql`cardinality("roles") > 0`),
  ],
);

// citus: tenant (PK and every unique lead with tenant_id; FKs to the reference tables only)
export const invitations = identityPgSchema.table(
  'invitations',
  {
    tenantId: uuid()
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    id: uuid().notNull().default(sql`uuidv7()`),
    /** Normalised like users.email; acceptance requires the logged-in user's email to match. */
    email: text().notNull(),
    roles: tenantRole().array().notNull(),
    /** sha256 hex of the mailed token. */
    tokenHash: text().notNull(),
    invitedBy: uuid()
      .notNull()
      .references(() => users.id),
    expiresAt: timestamptz().notNull(),
    acceptedAt: timestamptz(),
    createdAt: timestamptz().notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ name: 'invitations_tenant_id_id_pk', columns: [t.tenantId, t.id] }),
    uniqueIndex('invitations_tenant_id_token_hash_uq').on(t.tenantId, t.tokenHash),
    // findByTokenHash: a multi-shard system read (one index probe per shard once distributed).
    index('invitations_token_hash_idx').on(t.tokenHash),
  ],
);

export const usersRelations = relations(users, ({ many }) => ({
  sessions: many(sessions),
}));

export const sessionsRelations = relations(sessions, ({ one }) => ({
  user: one(users, { fields: [sessions.userId], references: [users.id] }),
}));

/**
 * Everything `DatabaseModule.forRootAsync({ schema })` needs for this context. The monolith
 * spreads it with the other contexts: `{ ...identitySchema, ...billingSchema }` (keys are unique).
 */
export const identitySchema = {
  userRole,
  tenantRole,
  users,
  sessions,
  tenants,
  memberships,
  invitations,
  usersRelations,
  sessionsRelations,
};

export type IdentitySchema = typeof identitySchema;
export type UserRow = typeof users.$inferSelect;
export type NewUserRow = typeof users.$inferInsert;
export type SessionRow = typeof sessions.$inferSelect;
export type NewSessionRow = typeof sessions.$inferInsert;
export type TenantRow = typeof tenants.$inferSelect;
export type MembershipRow = typeof memberships.$inferSelect;
export type InvitationRow = typeof invitations.$inferSelect;
